export interface QuizResult {
  level: number;
  classInfo: ConsciousnessClassInfo;
  dominantVector: CognitionVector;
  vectorInfo: CognitionVectorInfo;
  vectorScores: Record<CognitionVector, number>;
  totalScore: number;
}

export function calculateConsciousnessResult(selectedOptionIndices: number[]): QuizResult {
  let totalPoints = 0;
  const vectorScores: Record<CognitionVector, number> = {
    visual_analogies: 0,
    exact_sciences: 0,
    pragmatic: 0,
    philosophical: 0,
    spiritual: 0
  };

  selectedOptionIndices.forEach((optIdx, qIdx) => {
    const question = CONSCIOUSNESS_QUIZ_QUESTIONS[qIdx];
    if (question && question.options[optIdx]) {
      const opt = question.options[optIdx];
      totalPoints += opt.points;
      vectorScores[opt.vector] = (vectorScores[opt.vector] || 0) + 1;
    }
  });

  const avgPoints = totalPoints / (selectedOptionIndices.length || 1);
  let calculatedLevel = Math.round(avgPoints);
  if (calculatedLevel < 1) calculatedLevel = 1;
  if (calculatedLevel > 11) calculatedLevel = 11;

  let dominantVector: CognitionVector = 'visual_analogies';
  let maxVectorScore = -1;
  (Object.keys(vectorScores) as CognitionVector[]).forEach((vec) => {
    if (vectorScores[vec] > maxVectorScore) {
      maxVectorScore = vectorScores[vec];
      dominantVector = vec;
    }
  });

  const classInfo = CONSCIOUSNESS_CLASSES.find(c => c.level === calculatedLevel) || CONSCIOUSNESS_CLASSES[0];
  const vectorInfo = COGNITION_VECTORS[dominantVector];

  return {
    level: calculatedLevel,
    classInfo,
    dominantVector,
    vectorInfo,
    vectorScores,
    totalScore: totalPoints
  };
}